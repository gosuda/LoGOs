// Package editmap holds the edit map of one lowered file: the record the
// compiler writes beside each ejected Go text so a reader can translate
// byte offsets between the original loGo/s source and the lowered text.
// The compiler builds the map, the language server proxy reads it for
// position translation, and other cmd tools read it to attribute findings
// to their original offsets.
package editmap

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
)

// Suffix is appended to the name of an ejected Go file to name its edit
// map: a.lgo ejects to a.go and a.go.edits.
const Suffix = ".edits"

// Version is the version field of an EditMap. A reader rejects any other
// value. Version 2 added Segments; the Edits array alone cannot tell a
// generated byte from a copied one, so a reader of a version 2 map makes
// every origin decision through Segments.
const Version = 2

// Segment is one run of the lowered text: the Len bytes at Out are either
// a verbatim copy of the Len bytes of the original file at Orig, or, with
// Orig negative, compiler-generated. The segments of one edit map
// partition [0, Out) of the lowered text in order.
type Segment struct {
	Out  int `json:"out"`
	Len  int `json:"len"`
	Orig int `json:"orig"` // -1 marks generated bytes
}

// EditSpan is one applied edit of a lowering: the bytes of the original
// text from Start up to End became Len bytes of the lowered text. An
// insertion has Start equal to End. Spans come in source order and never
// overlap, so a reader can map offsets between the two texts.
type EditSpan struct {
	Start int `json:"start"`
	End   int `json:"end"`
	Len   int `json:"len"`
}

// EditMap is the JSON document beside an ejected file. It lists the edits
// that turned the original source into the ejected text, as byte spans of
// the original, so a reader can map any offset of one text to the other.
// Source is the base name of the original file, Size and Out are the byte
// sizes of the original and ejected texts; a reader checks them against
// the texts it holds before it trusts the spans.
type EditMap struct {
	Version  int        `json:"version"`
	Source   string     `json:"source"`
	Size     int        `json:"size"`
	Out      int        `json:"out"`
	Edits    []EditSpan `json:"edits"`
	Segments []Segment  `json:"segments"`
}

// Write writes the edit map of one ejected file to path. It uses
// encoding/json, not encoding/json/v2: the bootstrap toolchain builds
// this package, and v2 is an experiment there.
func Write(path, source string, size, out int, spans []EditSpan, segments []Segment) error {
	data, err := json.Marshal(EditMap{
		Version:  Version,
		Source:   filepath.Base(source),
		Size:     size,
		Out:      out,
		Edits:    spans,
		Segments: segments,
	})
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(data, '\n'), 0o666)
}

// Edge says which side of an insertion a boundary offset belongs to. A
// leading offset is the start of a token, and sits after text inserted at
// that offset; a trailing offset is the end of a token, and sits before
// it.
type Edge int

const (
	Leading Edge = iota
	Trailing
)

// Map translates byte offsets between an original text and its lowered
// text. It rests on the segments of the lowering, which mark the bytes
// the lowering copied unchanged, so the operand of a ? statement, say,
// still maps exactly.
type Map struct {
	SrcLen   int
	OutLen   int
	Segments []Segment
}

// New checks m against the two texts and builds the map.
func New(src, out []byte, m EditMap) (*Map, error) {
	if err := Check(src, out, m); err != nil {
		return nil, err
	}
	return &Map{SrcLen: len(src), OutLen: len(out), Segments: m.Segments}, nil
}

// Check rejects a map that cannot describe the transformation from src
// to out: another version, other sizes, edits that are unordered,
// overlap, leave the text, or do not add up to the lowered size, or
// segments that do not partition the lowered text, leave the source, or
// disagree with the texts they claim to copy.
func Check(src, out []byte, m EditMap) error {
	if m.Version != Version {
		return fmt.Errorf("edit map for %s has unsupported version %d", m.Source, m.Version)
	}
	if m.Size != len(src) || m.Out != len(out) {
		return fmt.Errorf("edit map for %s does not match its texts", m.Source)
	}
	prev, delta := 0, 0
	for _, s := range m.Edits {
		if !s.fits(prev, len(src)) {
			return fmt.Errorf("edit map for %s holds the invalid span %d:%d", m.Source, s.Start, s.End)
		}
		prev = s.End
		delta += s.Len - (s.End - s.Start)
	}
	if len(src)+delta != len(out) {
		return fmt.Errorf("edit map for %s does not add up to the lowered size", m.Source)
	}
	next := 0
	for _, s := range m.Segments {
		if s.Len <= 0 || s.Out != next {
			return fmt.Errorf("edit map for %s has segments that do not partition the lowered text", m.Source)
		}
		if s.Len > len(out)-s.Out {
			return fmt.Errorf("edit map for %s has segments that do not cover the lowered text", m.Source)
		}
		end := s.Out + s.Len
		if s.Orig < -1 {
			return fmt.Errorf("edit map for %s holds the invalid segment %d:%d", m.Source, s.Out, end)
		}
		if s.Orig >= 0 {
			if s.Len > len(src)-s.Orig {
				return fmt.Errorf("edit map for %s holds the copy segment %d:%d outside its source", m.Source, s.Out, end)
			}
			if !bytes.Equal(src[s.Orig:s.Orig+s.Len], out[s.Out:end]) {
				return fmt.Errorf("edit map for %s holds the copy segment %d:%d that differs from its source", m.Source, s.Out, end)
			}
		}
		next = end
	}
	if next != len(out) {
		return fmt.Errorf("edit map for %s has segments that do not cover the lowered text", m.Source)
	}
	return nil
}

// fits reports whether s starts at or after prev, the end of the span
// before it, ends inside a text of size bytes, and does not start after
// it ends.
func (s EditSpan) fits(prev, size int) bool {
	return s.Start >= prev && s.End >= s.Start && s.End <= size && s.Len >= 0
}

// LoweredOffset maps an offset of the original text to the lowered text.
// It reports false when o lies in text the lowering deleted: a deleted
// offset has no lowered position of its own. At a seam the side of e
// decides: the trailing edge stays before text inserted at o and the
// leading edge goes after it, unless the inserted text replaces deleted
// bytes, in which case both edges stay before it.
func (m *Map) LoweredOffset(o int, e Edge) (int, bool) {
	if m.SrcLen == 0 && o == 0 {
		if e == Trailing {
			return 0, true
		}
		return m.OutLen, true
	}
	if o == 0 && e == Trailing {
		for _, s := range m.Segments {
			if s.Orig >= 0 {
				if s.Orig == 0 && s.Out > 0 {
					return 0, true
				}
				break
			}
		}
	}
	for i, s := range m.Segments {
		if s.Orig < 0 {
			continue
		}
		if o >= s.Orig && o < s.Orig+s.Len {
			return s.Out + o - s.Orig, true
		}
		if o != s.Orig+s.Len {
			continue
		}
		if e == Trailing {
			return s.Out + s.Len, true
		}
		if i+1 < len(m.Segments) && m.Segments[i+1].Orig < 0 {
			g := m.Segments[i+1]
			pure := (i+2 >= len(m.Segments) && o == m.SrcLen) ||
				(i+2 < len(m.Segments) && m.Segments[i+2].Orig == o)
			if pure {
				return g.Out + g.Len, true
			}
		}
		return s.Out + s.Len, true
	}
	return 0, false
}

// LoweredOffsetNear maps an offset of deleted original text the way
// LoweredOffset maps a seam: the leading edge sits at the end of the
// nearest copied text before o in the original, where its replacement
// starts, and the trailing edge sits at the start of the nearest copied
// text after o. It compares original offsets, not lowered ones: a
// lowering may move or duplicate exact chunks, so lowered order need not
// follow original order.
func (m *Map) LoweredOffsetNear(o int, e Edge) int {
	if v, ok := m.LoweredOffset(o, e); ok {
		return v
	}
	if e == Trailing {
		bestOrig := -1
		bestOut := m.OutLen
		for _, s := range m.Segments {
			if s.Orig < 0 || s.Orig <= o {
				continue
			}
			if bestOrig == -1 || s.Orig < bestOrig || (s.Orig == bestOrig && s.Out < bestOut) {
				bestOrig = s.Orig
				bestOut = s.Out
			}
		}
		return bestOut
	}
	bestEnd := -1
	bestOut := 0
	for _, s := range m.Segments {
		if s.Orig < 0 {
			continue
		}
		end := s.Orig + s.Len
		if end > o {
			continue
		}
		outEnd := s.Out + s.Len
		if bestEnd == -1 || end > bestEnd || (end == bestEnd && outEnd < bestOut) {
			bestEnd = end
			bestOut = outEnd
		}
	}
	return bestOut
}

// genAnchors returns the original span a generated run stands for: it
// runs from the end of the preceding copied text, prevEnd, to the start
// of the next copied text.
func (m *Map) genAnchors(i, prevEnd int) (start, end int) {
	start, end = prevEnd, m.SrcLen
	for _, s := range m.Segments[i+1:] {
		if s.Orig >= 0 {
			end = s.Orig
			break
		}
	}
	return start, end
}

// OriginalOffset maps an offset of the lowered text to the original text.
// The second result reports whether o lies strictly inside generated
// text: a boundary offset, including the end of the text, counts as the
// user's own text. A generated offset still maps to the original text
// that produced it, the start of it on the leading edge and the end of it
// on the trailing edge. At the seam of a deletion, the trailing edge
// stays before the deleted text and the leading edge goes after it.
func (m *Map) OriginalOffset(o int, e Edge) (int, bool) {
	if o == m.OutLen && len(m.Segments) > 0 {
		last := m.Segments[len(m.Segments)-1]
		if last.Orig < 0 {
			return m.SrcLen, false
		}
		if end := last.Orig + last.Len; end == m.SrcLen {
			return end, false
		} else if e == Trailing {
			return end, false
		} else {
			return m.SrcLen, false
		}
	}
	prevEnd := 0
	for i, s := range m.Segments {
		end := s.Out + s.Len
		if o < s.Out || o >= end {
			if s.Orig >= 0 {
				prevEnd = s.Orig + s.Len
			}
			continue
		}
		if s.Orig >= 0 {
			if o == s.Out && s.Orig > prevEnd && e == Trailing {
				return prevEnd, false
			}
			return s.Orig + o - s.Out, false
		}
		if o == s.Out {
			return prevEnd, false
		}
		start, finish := m.genAnchors(i, prevEnd)
		if e == Trailing {
			return finish, true
		}
		return start, true
	}
	return m.SrcLen, false
}

// WidenOverGenerated expands start and end to the anchors of every
// generated run overlapping [loStart, loEnd). Anchors that run backwards
// belong to generated text between moved copies and stay out: widening to
// them would claim almost the whole original text.
func (m *Map) WidenOverGenerated(loStart, loEnd, start, end int) (int, int) {
	prevEnd := 0
	for i, s := range m.Segments {
		segEnd := s.Out + s.Len
		if s.Orig >= 0 {
			prevEnd = s.Orig + s.Len
			continue
		}
		if s.Out >= loEnd || segEnd <= loStart {
			continue
		}
		aStart, aFinish := m.genAnchors(i, prevEnd)
		if aStart > aFinish {
			continue
		}
		start = min(start, aStart)
		end = max(end, aFinish)
	}
	return start, end
}
